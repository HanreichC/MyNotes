/** Keys as a German keyboard names them, or as an English one does: keys('Strg+Umschalt+T') */
export const keys = (s) => (lang === 'en' ? s.replace(/[\p{L}↑↓]+/gu, (w) => KEYS_EN[w] ?? w) : s);

