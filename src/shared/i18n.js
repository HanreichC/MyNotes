// German or English. The German text is the key, EN translates it, and a text missing there stays German.
// The window reads its language once when it loads (preload.cjs), the main process gets it from settings.
// tests/i18n.test.js checks that every t('…') in src has its English text, and that nothing in EN is left over.

let lang = globalThis.api?.language === 'en' ? 'en' : 'de';

export const language = () => lang;
/** 'de', 'de-AT' … is German, anything else English. */
export const setLanguage = (l) => { lang = /^de\b/.test(l) ? 'de' : 'en'; };
export const locale = () => (lang === 'en' ? 'en-GB' : 'de-DE');

/** t('„{name}“ ist leer.', { name }) */
export function t(key, params) {
  const s = (lang === 'en' && EN[key]) || key;
  return params ? s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m)) : s;
}

